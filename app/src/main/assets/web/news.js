function makeElement(tagName, className, text) {
  const element = document.createElement(tagName);
  if (className) element.className = className;
  if (text) element.textContent = text;
  return element;
}

function createNewsArtwork(newsItem, className, eager = false) {
  const artwork = makeElement("figure", className);
  const image = makeElement("img", "news-card__photo");
  image.src = newsItem.image;
  image.alt = newsItem.imageAlt;
  image.loading = eager ? "eager" : "lazy";
  image.decoding = "async";

  const credit = makeElement(
    "a",
    "news-card__credit",
    `Foto: ${newsItem.imageCredit} · ${newsItem.imageLicense} · Wikimedia Commons`,
  );
  credit.href = newsItem.imagePage;
  credit.target = "_blank";
  credit.rel = "noopener noreferrer";
  credit.setAttribute("aria-label", `Crédito y licencia de la foto: ${newsItem.imageCredit}`);
  artwork.append(image, credit);
  return artwork;
}

function createNewsDialog() {
  const dialog = makeElement("dialog", "news-dialog");
  dialog.setAttribute("aria-labelledby", "news-dialog-title");
  const artwork = createNewsArtwork(NEWS[0], "news-dialog__art");
  const body = makeElement("div", "news-dialog__body");
  const category = makeElement("div", "news-card__category");
  const title = makeElement("h2", "news-dialog__title");
  title.id = "news-dialog-title";
  const summary = makeElement("p", "news-dialog__summary");
  const paragraphs = makeElement("div", "news-dialog__paragraphs");
  const tags = makeElement("div", "news-dialog__tags");
  const footer = makeElement("div", "news-dialog__footer");
  const closeButton = makeElement("button", "news-dialog__close", "CERRAR");
  closeButton.type = "button";
  closeButton.addEventListener("click", () => dialog.close());

  body.append(category, title, summary, paragraphs, tags);
  footer.append(closeButton);
  dialog.append(artwork, body, footer);
  dialog.addEventListener("cancel", () => dialog.close());
  dialog.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      event.preventDefault();
      dialog.close();
    }
  });
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) dialog.close();
  });

  return {
    dialog,
    category,
    title,
    summary,
    paragraphs,
    tags,
  };
}

function initializeNews() {
  const hero = document.querySelector("#inicio");
  const main = document.querySelector("main");
  if ((!hero && !main) || document.querySelector("#noticias")) return false;

  const style = makeElement("style");
  style.textContent = NEWS_STYLES;
  document.head.append(style);
  if (document.querySelector("main > .brand")) {
    document.body.classList.add("news-pwa");
  }

  const section = makeElement("section", "news-feed");
  section.id = "noticias";
  section.setAttribute("aria-labelledby", "news-feed-heading");

  const inner = makeElement("div", "news-feed__inner");
  inner.append(makeElement("span", "news-feed__eyebrow", "Fuera del dial"));

  const heading = makeElement("h2", "news-feed__heading", "Noticias");
  heading.id = "news-feed-heading";
  inner.append(
    heading,
    makeElement(
      "p",
      "news-feed__intro",
      "Novedades, discos y recuerdos que siguen sonando.",
    ),
  );

  const grid = makeElement("div", "news-grid");
  const dialogContent = createNewsDialog();
  NEWS.forEach((newsItem, index) => {
    const card = makeElement("article", "news-card");
    const artwork = createNewsArtwork(
      newsItem,
      "news-card__art",
      index === 0,
    );
    const content = makeElement("div", "news-card__content");
    content.append(
      makeElement("span", "news-card__category", newsItem.category),
      makeElement("h3", "news-card__title", newsItem.title),
      makeElement("p", "news-card__summary", newsItem.summary),
    );

    const readButton = makeElement(
      "button",
      "news-card__button",
      "LEER NOTICIA",
    );
    readButton.type = "button";
    readButton.setAttribute("aria-haspopup", "dialog");
    readButton.addEventListener("click", () => {
      dialogContent.category.textContent = newsItem.category;
      dialogContent.title.textContent = newsItem.title;
      dialogContent.summary.textContent = newsItem.summary;
      const artworkImage = dialogContent.dialog.querySelector(
        ".news-dialog__art .news-card__photo",
      );
      const artworkCredit = dialogContent.dialog.querySelector(
        ".news-dialog__art .news-card__credit",
      );
      if (!(artworkImage instanceof HTMLImageElement) || !artworkCredit) {
        throw new Error("No se encontró la imagen de la noticia.");
      }
      artworkImage.src = newsItem.image;
      artworkImage.alt = newsItem.imageAlt;
      artworkCredit.href = newsItem.imagePage;
      artworkCredit.textContent = `Foto: ${newsItem.imageCredit} · ${newsItem.imageLicense} · Wikimedia Commons`;
      artworkCredit.setAttribute(
        "aria-label",
        `Crédito y licencia de la foto: ${newsItem.imageCredit}`,
      );
      dialogContent.paragraphs.replaceChildren(
        ...newsItem.paragraphs.map((paragraph) =>
          makeElement("p", "news-dialog__paragraph", paragraph),
        ),
      );
      dialogContent.tags.replaceChildren(
        ...newsItem.tags.map((tag) =>
          makeElement("span", "news-dialog__tag", tag),
        ),
      );
      dialogContent.dialog.showModal();
    });

    content.append(readButton);
    card.append(artwork, content);
    grid.append(card);
  });

  inner.append(grid);
  section.append(inner);
  if (hero) {
    hero.after(section);
  } else {
    main.after(section);
  }
  document.body.append(dialogContent.dialog);
  return true;
}

if (!initializeNews()) {
  const observer = new MutationObserver(() => {
    if (initializeNews()) observer.disconnect();
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
